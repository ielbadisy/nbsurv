test_that("formula transforms work in evaluate, calibration, varimp, cv and plot", {
  d <- simulate_nbsurv_data(n = 200, censor_rate = 0.2, seed = 3)
  d$z <- exp(d$x1); d2 <- transform(d, lz = log1p(z))
  f <- nbsurv(survival::Surv(time, status) ~ log1p(z) + grp, d)
  g <- nbsurv(survival::Surv(time, status) ~ lz + grp, d2)
  expect_equal(evaluatenbsurv(f, d, times = 1:3), evaluatenbsurv(g, d2, times = 1:3))
  vf <- varimpnbsurv(f, d, times = 1:3, n_repeats = 3, seed = 1)
  vg <- varimpnbsurv(g, d2, times = 1:3, n_repeats = 3, seed = 1)
  expect_equal(vf$importance, vg$importance)
  expect_true(vf$importance[vf$feature == "log1p(z)"] != 0)
  pdf(NULL); on.exit(grDevices::dev.off())
  expect_equal(calibrationplotnbsurv(f, d, horizon = 2), calibrationplotnbsurv(g, d2, horizon = 2))
  expect_equal(unname(plot(f, times = 1:3)), unname(plot(g, times = 1:3)))
  cf <- cvnbsurv(survival::Surv(time, status) ~ log1p(z) + grp, d, folds = 3, times = 1:3, seed = 1)
  cg <- cvnbsurv(survival::Surv(time, status) ~ lz + grp, d2, folds = 3, times = 1:3, seed = 1)
  expect_equal(cf$summary, cg$summary)
})
